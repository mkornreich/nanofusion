    public void runSimulation(Simulation simulation, VisualizationLauncher launcher) {
        this.launcher = launcher;
        ProgressThread thread = new ProgressThread();
        thread.setSimulation(simulation);
        thread.start();
    }
    
   private class ProgressThread extends Thread {

        private Simulation simulation;

        public void setSimulation(Simulation simulation) {
            this.simulation=simulation;
        }

        public void run() {
            Simulator simulator = new Simulator(simulation.getProperties());
            List<Lattice> result = new ArrayList<Lattice>();
            List<Double> minDistances = new ArrayList<Double>();
            Lattice lattice = simulator.getLattice();
            result.add(lattice);
            int iterations = simulation.getProperties().getIterations();
            pbSimulationProgress.setMaximum(iterations - 1);
            //Simula
            for (int ii=0; ii<iterations; ii++) {
                lattice = simulator.step(ii);
                result.add(lattice);
                //minDistances.add(simulator.getMinDistance().doubleValue());
                //System.out.println("" + simulator.getMinDistance().doubleValue());
                pbSimulationProgress.setValue(ii);
            }
            simulation.setResults(result);
            simulation.setPairs(simulator.getPairs());
            //simulation.setMinDistances(minDistances);
            btnDone.setEnabled(true);
        }
    };

    
