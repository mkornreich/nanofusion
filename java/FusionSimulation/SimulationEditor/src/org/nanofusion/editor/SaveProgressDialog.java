    public void saveSimulation(Simulation simulation, SaveFinishListener listener) {
        this.listener = listener;
        btnDone.setEnabled(false);
        ProgressThread thread = new ProgressThread();
        thread.setSimulation(simulation);
        thread.start();
    }
    
   private class ProgressThread extends Thread {

        private Simulation simulation;

        public void setSimulation(Simulation simulation) {
            this.simulation=simulation;
        }

        public void run() {
            //The default dir to use if no value is stored
            File home = new File (System.getProperty("user.home") + File.separator + "lib");
            //Now build a file chooser and invoke the dialog in one line of code
            //"libraries-dir" is our unique key
            File toAdd = new FileChooserBuilder ("libraries-dir").setTitle("Add Library").
                setDefaultWorkingDirectory(home).setApproveText("Add").showSaveDialog();
            //Result will be null if the user clicked cancel or closed the dialog w/o OK
            int iterations = simulation.getProperties().getIterations();
            pbSimulationProgress.setMaximum(iterations - 1);
            if (toAdd != null) {
               String fileName = toAdd.getAbsolutePath();
               if (!fileName.endsWith(".json")) {
                   fileName = fileName + ".json";
               }
               BufferedWriter writer = null;
               try {
                    writer = new BufferedWriter( new FileWriter( fileName));
                    Gson gson = new Gson();
                    writer.write("{\n");
                    writer.write("properties: ");
                    gson.toJson(simulation.getProperties(), writer);
                    writer.write(",\n");
                    writer.write("results:\n");
                    writer.write("[\n");
                    int ii=0;
                    for (Lattice lattice: simulation.getResults()) {
                        gson.toJson(lattice, writer);
                        writer.write(",\n");
                        writer.flush();
                        pbSimulationProgress.setValue(ii++);
                    }
                    writer.write("]\n");
                    writer.write("}");
               }
               catch ( IOException e) {
               }
               finally {
                   try {
                       if ( writer != null) {
                            writer.close( );
                       }
                   }
                   catch ( IOException e) { 
                   }
               }           
               btnDone.setEnabled(true);
            }
            else {
                btnDoneActionPerformed(null);
            }
            //Simula
        }
    };

    
