    private void displayFrame() {
        String dimension = btnDimension.getText();
        Lattice lattice = simulation.get(frameNo);
        lblCompTime.setText(lattice.getExecutionTime() + "");
        if (dimension.equals("3d")) {
            SimulationFrameDisplayer.displayFrame(simulation, pnlPlot, frameNo, lblFrameNo);            
        }
        else {
            int z = sldZ.getValue();
            SimulationFrameDisplayer.displayFrame2D(simulation, pnlPlot, frameNo, lblFrameNo, z);    
        }
    }
    
    private void startVisualization() {
        this.frameNo = 0;
        if (simulation.size()>1) {
            btnNext.setEnabled(true);
            btnLast.setEnabled(true);
            btnAnimate.setEnabled(true);
            lblTotalFrames.setText(simulation.size() + "");
        }
        btnRestart.setEnabled(false);
        btnPrevious.setEnabled(false);
        displayFrame();
        pnlPlot.setVisible(true);
    }
    
    public void visualize(List<Lattice> simulation, int zSize) {
        this.particleNo = 0;
        this.simulation = simulation;
        sldZ.setValue(0);
        sldZ.setMaximum(zSize - 1);
        startVisualization();
        sldFrames.setMaximum(simulation.size());
    }

    private void runAnimation() {
        btnAnimate.setEnabled(false);
        btnRestart.setEnabled(false);
        btnNext.setEnabled(false);
        btnPrevious.setEnabled(false);
        //sldSpeed.setEnabled(false);
        AnimationThread thread = new AnimationThread();
        thread.start();
    }

    private class AnimationThread extends Thread {
 
        public void run() {
            int totalFrames = simulation.size();
            lblTotalFrames.setText(totalFrames + "");
            int sleepTime = 50;
            int speed = sldSpeed.getValue();
            sleepTime = 1000/speed;
            String dimension = btnDimension.getText();
            if (dimension.equals("3d")) {
                for (int frameNo=0; frameNo<totalFrames; frameNo++) {
                    Lattice lattice = simulation.get(frameNo);
                    lblCompTime.setText(lattice.getExecutionTime() + "");
                    //sldFrames.setValue(frameNo + 1);
                    SimulationFrameDisplayer.displayFrame(simulation, pnlPlot, frameNo, lblFrameNo);
                    try {
                        Thread.sleep(sleepTime);
                    }
                    catch (Exception e) {
                    }
                }
            }
            else {
                int z = sldZ.getValue();
                for (int frameNo=0; frameNo<totalFrames; frameNo++) {
                    Lattice lattice = simulation.get(frameNo);
                    lblCompTime.setText(lattice.getExecutionTime() + "");
                    sldFrames.setValue(frameNo + 1);
                    SimulationFrameDisplayer.displayFrame2D(simulation, pnlPlot, frameNo, lblFrameNo, z);
                    try {
                        Thread.sleep(sleepTime);
                    }
                    catch (Exception e) {
                    }
                }
            }
            btnAnimate.setEnabled(true);
            btnRestart.setEnabled(true);
            btnPrevious.setEnabled(true);
            btnNext.setEnabled(false);
            btnLast.setEnabled(false);
            ///sldSpeed.setEnabled(true);
        }
    };
    
    private class SliderFrameChanger extends Thread {
        
        private boolean available = true;
        
        public void run () {
            available = false;
            displayFrame();
            available = true;
        }
        
    };

