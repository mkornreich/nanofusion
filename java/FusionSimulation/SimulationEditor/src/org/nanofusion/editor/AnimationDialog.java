    private void runAnimation() {
        btnDone.setEnabled(false);
        btnReplay.setEnabled(false);
        //sldSpeed.setEnabled(false);
        AnimationThread thread = new AnimationThread();
        thread.start();
    }

    public void animateSimulation(List<Lattice> simulation) {
        this.simulation = simulation;
        runAnimation();
    }

    private class AnimationThread extends Thread {
 
        public void run() {
            int totalFrames = simulation.size();
            lblTotalFrames.setText(totalFrames + "");
            int sleepTime = 50;
            //int speed = 50 - sldSpeed.getValue();
            //sleepTime = 20 + 20*(speed - 1);
            for (int frameNo=0; frameNo<totalFrames; frameNo++) {
                SimulationFrameDisplayer.displayFrame(simulation, pnlFrame, frameNo, lblFrameNo);
                try {
                    Thread.sleep(sleepTime);
                }
                catch (Exception e) {
                }
            }
            btnDone.setEnabled(true);
            btnReplay.setEnabled(true);
            ///sldSpeed.setEnabled(true);
        }
    };
